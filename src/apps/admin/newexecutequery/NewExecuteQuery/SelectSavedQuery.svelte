      <col width="15%" />
      <col width="20%" />
    </colgroup>
    <tbody>
      {#each Object.entries($savedQueryList) as [filename, query] (filename)}
        <tr onclick={() => process.LoadSavedQuery(query)}>
          <td>{filename}</td>
          <td>{query.collectionName ?? "<unknown>"}</td>
          <td>{query.whereClauses?.length ?? "<none>"}</td>
          <td>{query.selectedColumns?.length ?? "<none>"}</td>
          <td>{query.generatedBy ?? "<unknown>"}</td>
          <td>{query.generatedAt ? dayjs(query.generatedAt).format("DD-MM-YYYY HH:mm:ss.SSS") : "<unknown>"}</td>
        </tr>
      {/each}
    </tbody>
  </table>
